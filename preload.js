const { contextBridge, ipcRenderer } = require('electron')

// Every on*() subscription returns an unsubscribe function (it used to return the ipcRenderer object, so "unlisten" calls threw
// and listeners stacked up on every page visit).
const on = (channel, cb) => {
  const handler = (_, d) => cb(d)
  ipcRenderer.on(channel, handler)
  return () => ipcRenderer.removeListener(channel, handler)
}

